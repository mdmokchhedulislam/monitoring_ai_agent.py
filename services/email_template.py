
import html


def create_approval_email(
    metrics,
    analysis,
    action,
    approve_url,
    reject_url
):

    cpu = metrics["cpu_usage"]
    ram = metrics["memory"]["usage_percent"]
    disk = metrics["disk"]["usage_percent"]

    safe_analysis = html.escape(str(analysis))
    safe_action = html.escape(str(action))

    safe_approve_url = html.escape(
        approve_url,
        quote=True
    )

    safe_reject_url = html.escape(
        reject_url,
        quote=True
    )

    return f"""
    <!DOCTYPE html>
    <html>
    <body style="
        font-family: Arial, sans-serif;
        background-color: #f4f4f4;
        padding: 20px;
    ">

        <div style="
            max-width: 600px;
            margin: auto;
            background: white;
            padding: 25px;
            border-radius: 10px;
        ">

            <h2 style="color: #dc2626;">
                DevOps AI Agent - Critical Alert
            </h2>

            <p>
                Critical system risk detected.
                Human approval is required.
            </p>

            <h3>System Metrics</h3>

            <ul>
                <li>CPU Usage: {cpu}%</li>
                <li>RAM Usage: {ram}%</li>
                <li>Disk Usage: {disk}%</li>
            </ul>

            <h3>AI Analysis</h3>

            <div style="
                background: #f8fafc;
                padding: 15px;
                border-radius: 6px;
            ">
                {safe_analysis}
            </div>

            <h3>Proposed Action</h3>

            <p>
                <strong>{safe_action}</strong>
            </p>

            <hr>

            <h3>Human Approval Required</h3>

            <p>
                Please review the system information
                before making your decision.
            </p>

            <div style="margin-top: 25px;">

                <a href="{safe_approve_url}"
                   style="
                       background-color: #16a34a;
                       color: white;
                       padding: 13px 25px;
                       text-decoration: none;
                       border-radius: 6px;
                       font-weight: bold;
                       display: inline-block;
                       margin-right: 10px;
                   ">
                    APPROVE
                </a>

                <a href="{safe_reject_url}"
                   style="
                       background-color: #dc2626;
                       color: white;
                       padding: 13px 25px;
                       text-decoration: none;
                       border-radius: 6px;
                       font-weight: bold;
                       display: inline-block;
                   ">
                    REJECT
                </a>

            </div>

            <p style="
                margin-top: 30px;
                color: #666;
                font-size: 12px;
            ">
                Approval links expire after 15 minutes.
                Opening a link does not approve or reject
                the action. You must confirm on the next page.
            </p>

            <hr>

            <p style="color: #888; font-size: 12px;">
                Generated by DevOps AI Agent.
            </p>

        </div>

    </body>
    </html>
    """
